  function tokenTranslate(text){
    let out = text;
    Object.keys(TOKEN_MAP).sort((a,b)=>b.length-a.length).forEach(key=>{
      out = out.split(key).join(TOKEN_MAP[key]);
    });
    return out;
  }

  function translateString(input){
    if(input == null) return input;
    const original = String(input);
    const lead = original.match(/^\s*/)?.[0] || "";
    const tail = original.match(/\s*$/)?.[0] || "";
    let core = original.slice(lead.length, original.length - tail.length);

    if(!core) return original;
    if(EXACT.has(core)) return lead + EXACT.get(core) + tail;

    // Visible record identifiers must remain identical to their stored keys.
    const identifiers=[];
    core=core.replace(/\b(?:NEED|SIG|REQ|CRS|DCS|HND|ORG|MU|TU|SURV|AUD)-[A-Z0-9-]+\b/g, value=>{
      identifiers.push(value);return '\uE000'+(identifiers.length-1)+'\uE001';
    });

    core = tokenTranslate(core);

    for(const [from,to] of PHRASES){
      if(core.includes(from)) core = core.split(from).join(to);
    }
    for(const [rx,to] of REGEX_RULES){
      core = core.replace(rx,to);
    }

    core=core.replace(/\uE000(\d+)\uE001/g,(_,index)=>identifiers[Number(index)]);
    return lead + core + tail;
  }

  PHRASES.sort((a,b)=>b[0].length-a[0].length);
  const SKIP_SELECTOR='script,style,code,pre,noscript,svg,textarea,[data-no-translate]';
  function shouldSkip(node){
    if(!node || !node.parentElement) return true;
    return !!node.parentElement.closest(SKIP_SELECTOR);
  }

  function translateNode(node){
    if(node.nodeType === Node.TEXT_NODE){
      if(shouldSkip(node)) return;
      const next = translateString(node.nodeValue);
      if(next !== node.nodeValue) node.nodeValue = next;
      return;
    }
    if(node.nodeType !== Node.ELEMENT_NODE) return;

    const el = node;
    if(el.closest(SKIP_SELECTOR)) return;
    // An option without value implicitly uses its label as submitted data.
    if(el.tagName==='OPTION'&&!el.hasAttribute('value'))el.setAttribute('value',el.textContent);

    ["placeholder","title","aria-label"].forEach(attr=>{
      if(el.hasAttribute(attr)){
        const oldVal = el.getAttribute(attr);
        const newVal = translateString(oldVal);
        if(newVal !== oldVal) el.setAttribute(attr,newVal);
      }
    });

    // Buton ve submit alanlarında görünen value değerlerini çevir; veri değerlerine dokunma.
    if(el instanceof HTMLInputElement && ["button","submit","reset"].includes(el.type)){
      const nv = translateString(el.value);
      if(nv !== el.value) el.value = nv;
    }

    for(const child of Array.from(el.childNodes)) translateNode(child);
  }

